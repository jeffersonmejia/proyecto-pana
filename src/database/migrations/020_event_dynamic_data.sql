    ADD COLUMN IF NOT EXISTS location VARCHAR(255) NULL AFTER event_time,
    ADD COLUMN IF NOT EXISTS meeting_point VARCHAR(255) NULL AFTER location,
    ADD COLUMN IF NOT EXISTS requirements VARCHAR(1000) NULL AFTER meeting_point;

