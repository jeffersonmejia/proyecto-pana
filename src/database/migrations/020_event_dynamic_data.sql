    ADD COLUMN IF NOT EXISTS email VARCHAR(254) NULL AFTER full_name,
    ADD COLUMN IF NOT EXISTS gender VARCHAR(50) NULL AFTER email,
    ADD COLUMN IF NOT EXISTS gender_other VARCHAR(100) NULL AFTER gender,
    ADD COLUMN IF NOT EXISTS category VARCHAR(100) NULL AFTER gender_other,
    ADD COLUMN IF NOT EXISTS phone VARCHAR(40) NULL AFTER category,
